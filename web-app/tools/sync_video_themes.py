#!/usr/bin/env python3
"""Writes static/js/video/themes.js from the Android app's VideoThemes.kt.

    python3 tools/sync_video_themes.py           # regenerate
    python3 tools/sync_video_themes.py --check   # fail if themes.js is out of date (CI)

The drawn backgrounds are defined once, in Kotlin; the web app's copy is generated from it so the
two can't drift. Each scene is (kind, [top, middle, land, light] as #rrggbb, features).
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
KOTLIN = HERE.parent.parent / "android-app-quran-player" / "app" / "src" / "main" / "java" / "com" / "quran" / "learnedplayer" / "video" / "VideoThemes.kt"
OUT = HERE.parent / "static" / "js" / "video" / "themes.js"

THEME = re.compile(r'theme\("(?P<key>[a-z_]+)",\s*"(?P<title>[^"]+)",(?P<body>.*?)\)\s*,?\s*(?=theme\(|\)\s*$|\n\s*\)\s*\n)', re.S)
SCENE = re.compile(r"scene\(SceneKind\.(?P<kind>[A-Z_]+),\s*(?P<colors>(?:0x[0-9A-Fa-f]{8},\s*){3}0x[0-9A-Fa-f]{8})(?P<features>(?:,\s*Feature\.[A-Z_]+)*)\)")


def parse(source):
    block = source[source.index("val all: List<VideoTheme> = listOf("):source.index("private val byKey")]
    themes = []
    for chunk in re.split(r"\n\s*theme\(", block)[1:]:
        head = re.match(r'"(?P<key>[a-z_]+)",\s*"(?P<title>[^"]+)",', chunk)
        scenes = []
        for m in SCENE.finditer(chunk):
            colors = ["#" + c.strip()[4:].lower() for c in m.group("colors").split(",")]
            features = re.findall(r"Feature\.([A-Z_]+)", m.group("features"))
            scenes.append([m.group("kind"), colors, features])
        themes.append({"key": head.group("key"), "title": head.group("title"), "variants": scenes})
    fallback = re.search(r'const val FALLBACK = "([a-z_]+)"', source).group(1)
    return themes, fallback


def render(themes, fallback):
    lines = [
        "// Generated by tools/sync_video_themes.py from the Android app's VideoThemes.kt. Don't edit:",
        "// change the Kotlin and regenerate. Each variant is [kind, [top, middle, land, light], features].",
        "//",
        "// Content norms: drawn scenes of sky, land, water, light and pattern only, never a person or an",
        "// animal; videos carry no music, only the recitation.",
        "",
        f"export const FALLBACK = {json.dumps(fallback)};",
        "",
        "export const THEMES = [",
    ]
    for t in themes:
        lines.append(f"  {{ key: {json.dumps(t['key'])}, title: {json.dumps(t['title'])}, variants: [")
        for kind, colors, features in t["variants"]:
            lines.append(f"    [{json.dumps(kind)}, {json.dumps(colors)}, {json.dumps(features)}],")
        lines.append("  ] },")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main():
    themes, fallback = parse(KOTLIN.read_text(encoding="utf-8"))
    if len(themes) < 40 or any(not t["variants"] for t in themes):
        sys.exit(f"Parsed {len(themes)} themes from {KOTLIN.name}; the format must have changed")
    text = render(themes, fallback)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT.relative_to(HERE.parent)} is out of date: run tools/sync_video_themes.py")
        print(f"themes.js is up to date ({len(themes)} themes)")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(HERE.parent)}: {len(themes)} themes, {sum(len(t['variants']) for t in themes)} scenes")


if __name__ == "__main__":
    main()
